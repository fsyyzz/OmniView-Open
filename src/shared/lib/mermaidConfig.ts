export function resolveMermaidPalette(themeOrIsDark?: ThemeId | string | boolean): MermaidThemePalette {
  if (typeof themeOrIsDark === 'string' && MERMAID_THEME_PALETTES[themeOrIsDark]) {
    return MERMAID_THEME_PALETTES[themeOrIsDark];
  }
  const isDark = typeof themeOrIsDark === 'boolean' ? themeOrIsDark : true;
  return isDark ? MERMAID_THEME_PALETTES.dark : MERMAID_THEME_PALETTES.light;
}

